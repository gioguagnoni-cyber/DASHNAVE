create or replace view public.v_push_daily
with (security_invoker = true)
as
select
  r.id,
  r.account_id,
  r.campaign_id,
  c.utm_campaign,
  c.display_name as label,
  r.reporting_date as date,
  r.report_id,
  r.generated_at,
  r.report_timezone,
  r.currency,
  r.is_partial,
  r.impressions,
  r.unfilled_impressions,
  r.viewable_impressions,
  r.clicks,
  r.source_ctr,
  r.gross_revenue,
  r.source_ecpm,
  case when r.impressions > 0 then r.clicks::numeric / r.impressions else null end as calculated_ctr,
  case when r.impressions > 0 then r.gross_revenue / r.impressions * 1000 else null end as calculated_ecpm
from public.push_daily_results r
join public.push_campaigns c
  on c.id = r.campaign_id and c.account_id = r.account_id;

create or replace view public.v_combined_daily
with (security_invoker = true)
as
with meta as (
  select
    account_id,
    date,
    max(badge) as meta_badge,
    count(distinct campaign_id) as meta_campaigns,
    sum(spend) as meta_spend,
    sum(cost) as meta_cost,
    sum(rev) as meta_gross_revenue,
    sum(rev_adj) as meta_net_revenue,
    sum(profit) as meta_profit
  from public.v_daily
  where typ = 'msgs'
  group by account_id, date
),
push as (
  select
    account_id,
    date,
    bool_or(is_partial) as push_is_partial,
    count(distinct campaign_id) as push_campaigns,
    sum(impressions) as push_impressions,
    sum(clicks) as push_clicks,
    sum(gross_revenue) as push_gross_revenue
  from public.v_push_daily
  group by account_id, date
)
select
  coalesce(m.account_id, p.account_id) as account_id,
  coalesce(m.date, p.date) as date,
  coalesce(m.meta_campaigns, 0) as meta_campaigns,
  coalesce(m.meta_spend, 0) as meta_spend,
  coalesce(m.meta_cost, 0) as meta_cost,
  coalesce(m.meta_gross_revenue, 0) as meta_gross_revenue,
  coalesce(m.meta_net_revenue, 0) as meta_net_revenue,
  coalesce(m.meta_profit, 0) as meta_profit,
  coalesce(p.push_campaigns, 0) as push_campaigns,
  coalesce(p.push_impressions, 0) as push_impressions,
  coalesce(p.push_clicks, 0) as push_clicks,
  coalesce(p.push_gross_revenue, 0) as push_gross_revenue,
  coalesce(m.meta_gross_revenue, 0) + coalesce(p.push_gross_revenue, 0) as total_gross_revenue,
  case
    when coalesce(m.meta_badge = 'parcial', false) or coalesce(p.push_is_partial, false)
      then 'parcial'
    else 'fechado'
  end as status
from meta m
full join push p
  on p.account_id = m.account_id and p.date = m.date;

grant select on public.v_push_daily to anon, authenticated;
grant select on public.v_combined_daily to anon, authenticated;

