-- Push Notification analytics live beside, never inside, Meta Ads campaign data.
-- The two source channels only meet in the read-only daily consolidation view.

create table public.push_campaigns (
  id bigint generated by default as identity primary key,
  account_id text not null references public.dashboard_accounts(meta_account_id),
  utm_campaign text not null,
  display_name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint push_campaigns_utm_not_blank check (btrim(utm_campaign) <> ''),
  constraint push_campaigns_account_utm_key unique (account_id, utm_campaign),
  constraint push_campaigns_id_account_key unique (id, account_id)
);

create table public.push_daily_results (
  id bigint generated by default as identity primary key,
  account_id text not null references public.dashboard_accounts(meta_account_id),
  campaign_id bigint not null,
  reporting_date date not null,
  report_id text not null,
  generated_at timestamptz,
  report_timezone text not null,
  currency text not null,
  is_partial boolean not null,
  impressions bigint not null default 0,
  unfilled_impressions bigint not null default 0,
  viewable_impressions bigint not null default 0,
  clicks bigint not null default 0,
  source_ctr numeric(14,8) not null default 0,
  gross_revenue numeric(18,2) not null default 0,
  source_ecpm numeric(18,6) not null default 0,
  source_key text not null,
  source_sha256 text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint push_daily_campaign_account_fk
    foreign key (campaign_id, account_id)
    references public.push_campaigns(id, account_id),
  constraint push_daily_account_date_campaign_key
    unique (account_id, reporting_date, campaign_id),
  constraint push_daily_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint push_daily_nonnegative_check check (
    impressions >= 0 and unfilled_impressions >= 0 and
    viewable_impressions >= 0 and clicks >= 0 and
    source_ctr >= 0 and gross_revenue >= 0 and source_ecpm >= 0
  )
);

create index push_daily_account_date_idx
  on public.push_daily_results (account_id, reporting_date desc);
create index push_daily_campaign_date_idx
  on public.push_daily_results (campaign_id, reporting_date desc);

create schema if not exists private;
create table private.push_import_batches (
  id bigint generated by default as identity primary key,
  batch_key text not null unique,
  account_id text not null references public.dashboard_accounts(meta_account_id),
  reporting_date date not null,
  report_id text not null,
  generated_at timestamptz,
  is_partial boolean not null,
  currency text not null,
  report_timezone text not null,
  source_name text not null,
  source_sha256 text not null,
  status text not null,
  totals jsonb not null,
  audit jsonb not null,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

